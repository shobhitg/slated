import AppKit

/// Watches the general pasteboard for new copies. macOS has no change notification, so it polls
/// `changeCount` (cheap) twice a second, like every clipboard manager.
@MainActor
public final class PasteboardWatcher {
  public struct Copy: Sendable {
    /// Plain text of the copy, if it has any.
    public var text: String?
    /// The copied image, for a copy without text (a screenshot, a browser's Copy Image, Preview).
    /// A copy with both (a spreadsheet's cells) counts as text.
    public var image: CopiedImage?
    /// Files copied in the Finder (or any app that copies file URLs), in order. Such a copy is files
    /// only: the names as text and the icon picture that come with them are left out.
    public var files: [URL]?
    /// Marked secret by the app that wrote it (`concealedTypes`): password managers, browsers' Copy
    /// Password. History keeps it masked, in memory only (or skips it, `clipboard.secrets`).
    public var isConcealed: Bool
    /// Marked temporary or made automatically (`transientTypes`): a text expander's paste, a generated
    /// value. Not a copy of the user's, so history never records it.
    public var isTransient: Bool
    /// Slated's own text, on the clipboard only while it pastes it (`slatedPasteType`).
    public var isSlatedPaste: Bool
    /// The app it was copied from: the one the copy names (`sourceType`), else the frontmost app when
    /// the copy was noticed.
    public var sourceApp: String?

    public init(
      text: String?, image: CopiedImage? = nil, files: [URL]? = nil, isConcealed: Bool = false,
      isTransient: Bool = false, isSlatedPaste: Bool = false, sourceApp: String? = nil
    ) {
      self.text = text
      self.image = image
      self.files = files
      self.isConcealed = isConcealed
      self.isTransient = isTransient
      self.isSlatedPaste = isSlatedPaste
      self.sourceApp = sourceApp
    }
  }

  /// An image's bytes as the app put them on the pasteboard.
  public struct CopiedImage: Sendable, Equatable {
    public var data: Data
    /// `.png` or `.tiff`.
    public var type: NSPasteboard.PasteboardType

    public init(data: Data, type: NSPasteboard.PasteboardType) {
      self.data = data
      self.type = type
    }
  }

  /// Image types history keeps, in order of preference: PNG is usually far smaller than TIFF.
  nonisolated public static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]

  /// Types apps use to say "this is a secret" (nspasteboard.org's ConcealedType, and 1Password's older
  /// marker). A copy with one is a secret even when it's also marked transient.
  public static let concealedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"]
  /// Types apps use to say "this isn't the user's copy, don't record it" (nspasteboard.org) plus older
  /// vendor conventions: text expanders' pastes, generated values.
  public static let transientTypes: Set<String> = [
    "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping", "Pasteboard generator type",
  ]
  nonisolated public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  nonisolated public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  /// The bundle identifier of the app that made the copy, as nspasteboard.org's convention has it: more
  /// reliable than the app in front (a password manager's menu bar helper, a copy made by a script).
  nonisolated public static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
  /// Marks text Slated puts on the clipboard only to paste it (a long hotstring replacement). History
  /// never records it, even with concealed items allowed: that setting is about other apps' copies.
  nonisolated public static let slatedPasteType = NSPasteboard.PasteboardType("io.github.slated.paste")

  public var onCopy: ((Copy) -> Void)?
  private let pasteboard: NSPasteboard
  private var timer: Timer?
  private var lastChangeCount: Int

  /// Change counts, by pasteboard, of writes that only put a clipboard back the way it was (after
  /// Slated pasted a hotstring's replacement through it): not copies.
  nonisolated(unsafe) private static var restoredChanges: [String: Set<Int>] = [:]
  nonisolated private static let restoredLock = NSLock()

  /// `pasteboard` is the general one; tests use a private one.
  public init(pasteboard: NSPasteboard = .general) {
    self.pasteboard = pasteboard
    lastChangeCount = pasteboard.changeCount
  }

  public func start() {
    guard timer == nil else { return }
    lastChangeCount = pasteboard.changeCount
    timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
      MainActor.assumeIsolated { self?.poll() }
    }
  }

  /// Tells watchers that `pasteboard`'s current contents were only put back, so they don't record them
  /// as a new copy: from the app in front, ignoring excluded apps, and returning items the user deleted.
  nonisolated public static func ignoreCurrentContents(of pasteboard: NSPasteboard) {
    let (name, count) = (pasteboard.name.rawValue, pasteboard.changeCount)
    restoredLock.withLock { _ = restoredChanges[name, default: []].insert(count) }
  }

  /// Whether change `count` only put `pasteboard` back. Forgets it, and older ones (written over before
  /// a poll saw them).
  nonisolated private static func wasRestored(_ count: Int, on pasteboard: NSPasteboard) -> Bool {
    let name = pasteboard.name.rawValue
    return restoredLock.withLock {
      let restored = restoredChanges[name]?.contains(count) ?? false
      let newer = restoredChanges[name]?.filter { $0 > count } ?? Set()
      restoredChanges[name] = newer.isEmpty ? nil : newer
      return restored
    }
  }

  public func stop() {
    timer?.invalidate()
    timer = nil
  }

  /// Puts `text` on the clipboard as the user's own copy (it will be picked up as a new copy).
  /// `pasteboard` is the general one; tests use a private one. A `secret` is marked concealed, so other
  /// clipboard managers keep it hidden too, and stays on this Mac (Universal Clipboard doesn't offer it
  /// to your other devices).
  public static func write(_ text: String, to pasteboard: NSPasteboard = .general, secret: Bool = false) {
    if secret {
      pasteboard.prepareForNewContents(with: .currentHostOnly)
    } else {
      pasteboard.clearContents()
    }
    pasteboard.setString(text, forType: .string)
    if secret { pasteboard.setString("", forType: concealedType) }
  }

  /// Puts an image back on the clipboard, in the type it was copied as.
  public static func write(_ image: CopiedImage, to pasteboard: NSPasteboard = .general) {
    pasteboard.clearContents()
    pasteboard.setData(image.data, forType: image.type)
  }

  /// Puts files back on the clipboard as file URLs, as the Finder copies them: the Finder pastes the
  /// files, Mail and Slack attach them, and each app decides what a text field gets.
  public static func write(files: [URL], to pasteboard: NSPasteboard = .general) {
    pasteboard.clearContents()
    pasteboard.writeObjects(files.map { $0 as NSURL })
  }

  /// The file URLs on the pasteboard, in order; empty when there are none (web links don't count).
  public static func fileURLs(on pasteboard: NSPasteboard) -> [URL] {
    let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
    return (objects as? [URL] ?? []).filter(\.isFileURL)
  }

  /// Reports a new copy, if there is one. Runs twice a second; internal for tests.
  func poll() {
    guard pasteboard.changeCount != lastChangeCount else { return }
    lastChangeCount = pasteboard.changeCount
    if Self.wasRestored(lastChangeCount, on: pasteboard) { return }
    let types = Set((pasteboard.types ?? []).map(\.rawValue))
    // Files come with their names as text and a picture of their icons: they're files, nothing else.
    let files = Self.fileURLs(on: pasteboard)
    let text = files.isEmpty ? pasteboard.string(forType: .string) : nil
    // Only a copy without text is an image: cells come with a picture of themselves.
    let image =
      text != nil || !files.isEmpty
      ? nil
      : Self.imageTypes.lazy.filter { types.contains($0.rawValue) }
        .compactMap { type in self.pasteboard.data(forType: type).map { CopiedImage(data: $0, type: type) } }.first
    let named = types.contains(Self.sourceType.rawValue) ? pasteboard.string(forType: Self.sourceType) : nil
    onCopy?(
      Copy(
        text: text, image: image, files: files.isEmpty ? nil : files,
        isConcealed: !types.isDisjoint(with: Self.concealedTypes),
        isTransient: !types.isDisjoint(with: Self.transientTypes),
        isSlatedPaste: types.contains(Self.slatedPasteType.rawValue),
        sourceApp: named.flatMap { $0.isEmpty ? nil : $0 } ?? NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    )
  }
}
