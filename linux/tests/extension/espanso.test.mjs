import assert from 'node:assert/strict';
import {test} from 'node:test';

import {
  buildEspansoMatches,
  convertDateFormat,
  espansoYaml,
  templateToEspanso,
  yamlQuote,
} from '../../gnome-extension/lib/platform/espanso.js';

const hotstring = (fields) => ({
  enabled: true,
  caseSensitive: true,
  fire: 'immediately',
  wordBoundary: false,
  method: 'auto',
  onlyInApps: [],
  exceptInApps: [],
  ...fields,
});

test('Unicode date patterns become chrono formats', () => {
  assert.equal(convertDateFormat('yyyy-MM-dd'), '%Y-%m-%d');
  assert.equal(convertDateFormat('dd/MM/yy'), '%d/%m/%y');
  assert.equal(convertDateFormat('EEEE, MMMM d'), '%A, %B %-d');
  assert.equal(convertDateFormat('EEE d MMM'), '%a %-d %b');
  assert.equal(convertDateFormat('h:mm a'), '%-I:%M %p');
  assert.equal(convertDateFormat('HH:mm:ss.SSS'), '%H:%M:%S.%3f');
  assert.equal(convertDateFormat("yyyy-MM-dd'T'HH:mm"), '%Y-%m-%dT%H:%M');
  assert.equal(convertDateFormat("'Week' w"), 'Week %V');
  assert.equal(convertDateFormat("h 'o''clock'"), "%-I o'clock");
  assert.equal(convertDateFormat('100%'), '100%%');
  assert.equal(convertDateFormat('ZZZZZ'), '%:z');
});

test('placeholders become espanso variables; braces and unknown tokens stay literal', () => {
  assert.deepEqual(templateToEspanso('Today is {date:yyyy-MM-dd}'), {
    replace: 'Today is {{slated_date_1}}',
    vars: [{name: 'slated_date_1', type: 'date', params: {format: '%Y-%m-%d'}}],
  });
  assert.deepEqual(templateToEspanso('{date} {time} {DATE}'), {
    replace: '{{slated_date}} {{slated_time}} {{slated_date}}',
    vars: [
      {name: 'slated_date', type: 'date', params: {format: '%b %-d, %Y'}},
      {name: 'slated_time', type: 'date', params: {format: '%-I:%M %p'}},
    ],
  });
  assert.deepEqual(templateToEspanso('{clipboard}!'), {
    replace: '{{slated_clipboard}}!',
    vars: [{name: 'slated_clipboard', type: 'clipboard'}],
  });
  assert.deepEqual(templateToEspanso('{{literal}} and {unknown}'), {replace: '{literal} and {unknown}', vars: []});
  assert.deepEqual(templateToEspanso('¯\\_(ツ)_/¯'), {replace: '¯\\_(ツ)_/¯', vars: []});
  assert.deepEqual(templateToEspanso('{date:yyyy} {date:MM} {date:yyyy}').vars.map((v) => v.name), ['slated_date_1', 'slated_date_2']);
});

test('hotstrings map to espanso match options', () => {
  const {matches, skipped, approximations} = buildEspansoMatches([
    hotstring({trigger: ';shrug', replacement: '¯\\_(ツ)_/¯'}),
    hotstring({trigger: 'brb', replacement: 'be right back', fire: 'afterDelimiter', wordBoundary: true}),
    hotstring({trigger: 'omw', replacement: 'on my way', caseSensitive: false, method: 'paste'}),
    hotstring({trigger: ';t', replacement: 'typed', method: 'type'}),
    hotstring({trigger: ';off', replacement: 'never', enabled: false}),
    hotstring({trigger: ';mail', replacement: 'x', onlyInApps: ['org.gnome.Evolution']}),
    hotstring({trigger: ';term', replacement: 'y', exceptInApps: ['org.gnome.Terminal']}),
    hotstring({trigger: ';act', replacement: '', action: {op: 'undo'}}),
    hotstring({trigger: ';late', replacement: 'z', fire: 'afterDelimiter'}),
  ]);
  assert.deepEqual(matches, [
    {trigger: ';shrug', replace: '¯\\_(ツ)_/¯'},
    {trigger: 'brb', replace: 'be right back', word: true},
    {trigger: 'omw', replace: 'on my way', propagate_case: true, force_mode: 'clipboard'},
    {trigger: ';t', replace: 'typed', force_mode: 'keys'},
    {trigger: ';term', replace: 'y'},
    {trigger: ';act', replace: ''},
    {trigger: ';late', replace: 'z', word: true},
  ]);
  assert.deepEqual(skipped, [{trigger: ';mail', reason: "onlyInApps: espanso can't tell apps apart on GNOME Wayland"}]);
  assert.deepEqual(
    approximations.map((a) => `${a.trigger}:${a.option}`),
    [';term:exceptInApps', ';act:action', ';late:fire'],
  );
});

test('hotstrings turned off produce nothing', () => {
  const result = buildEspansoMatches([hotstring({trigger: ';x', replacement: 'y'})], {enabled: false});
  assert.deepEqual(result, {matches: [], skipped: [], approximations: []});
});

test('YAML strings escape what YAML needs and keep unicode', () => {
  assert.equal(yamlQuote('plain'), '"plain"');
  assert.equal(yamlQuote('say "hi"\\now'), '"say \\"hi\\"\\\\now"');
  assert.equal(yamlQuote('line1\nline2\ttab'), '"line1\\nline2\\ttab"');
  assert.equal(yamlQuote('bell\u0007'), '"bell\\x07"');
  assert.equal(yamlQuote('ツ'), '"ツ"');
  assert.equal(yamlQuote('a b'), '"a\\u2028b"');
});

test('the match file is valid espanso YAML', () => {
  const {matches} = buildEspansoMatches([
    hotstring({trigger: ';today', replacement: '{date:yyyy-MM-dd}', wordBoundary: true}),
    hotstring({trigger: ';sig', replacement: 'Best,\nMe'}),
  ]);
  assert.equal(
    espansoYaml(matches),
    [
      '# Generated by Slated from ~/.config/slated/config.json (hotstrings).',
      '# Slated rewrites this file when the configuration changes: edit hotstrings in Slated instead.',
      'matches:',
      '  - trigger: ";today"',
      '    replace: "{{slated_date_1}}"',
      '    word: true',
      '    vars:',
      '      - name: slated_date_1',
      '        type: date',
      '        params:',
      '          format: "%Y-%m-%d"',
      '  - trigger: ";sig"',
      '    replace: "Best,\\nMe"',
      '',
    ].join('\n'),
  );
  assert.match(espansoYaml([]), /^matches: \[\]$/m);
});
