// Sensitive hotstrings through espanso (lib/platform/espanso.js): their text comes from secrets.json,
// as written (no placeholders), always typed (force_mode: keys), `{{` passed through an echo variable
// espanso doesn't interpret, a missing one left out, and the match file readable only by you.

import assert from 'node:assert/strict';
import {mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {after, test} from 'node:test';

import {createFakeGnome} from './fake-gnome.mjs';
import {MemoryLog} from './fixtures.mjs';

const gnome = createFakeGnome();
globalThis.__slatedGnomeFakes = gnome.modules;
globalThis.global = gnome.global;
const {buildEspansoMatches, espansoYaml, literalToEspanso, EspansoSync} = await import('../../gnome-extension/lib/platform/espanso.js');

const homes = [];
after(() => {
  for (const dir of homes) rmSync(dir, {recursive: true, force: true});
});

const hotstring = (fields) => ({
  enabled: true, caseSensitive: true, fire: 'immediately', wordBoundary: false, method: 'auto', onlyInApps: [], exceptInApps: [],
  ...fields,
});
const sensitive = (trigger, name, fields = {}) => hotstring({trigger, replacement: {secret: name}, ...fields});

test('a sensitive hotstring is written with its secret’s text, as written, always typed', () => {
  const secrets = {pw: 'hunter2 {date} {{x}} ✓', bank: '1234-5678', empty: ''};
  const {matches, skipped} = buildEspansoMatches([
    sensitive(';pw', 'pw', {method: 'paste'}),
    sensitive(';bank', 'bank', {wordBoundary: true, caseSensitive: false}),
    sensitive(';gone', 'not-here'),
    sensitive(';empty', 'empty'),
    hotstring({trigger: ';plain', replacement: 'Today: {date}'}),
    sensitive(';off', 'pw', {enabled: false}),
  ], {secrets});
  assert.deepEqual(matches[0], {
    trigger: ';pw', replace: '{{slated_text}}', force_mode: 'keys', sensitive: true,
    vars: [{name: 'slated_text', type: 'echo', params: {echo: 'hunter2 {date} {{x}} ✓'}, inject_vars: false}],
  }, 'never pasted, placeholders not expanded, braces passed through');
  assert.deepEqual(matches[1], {trigger: ';bank', replace: '1234-5678', word: true, propagate_case: true, force_mode: 'keys', sensitive: true});
  assert.deepEqual(matches[2], {trigger: ';empty', replace: '', force_mode: 'keys', sensitive: true});
  assert.equal(matches[3].trigger, ';plain');
  assert.equal(matches[3].sensitive, undefined);
  assert.ok(matches[3].vars?.length, 'ordinary placeholders still work');
  assert.equal(matches.length, 4);
  assert.deepEqual(skipped, [{trigger: ';gone', reason: "sensitive, and its text isn't on this computer yet (secrets.json)"}]);
  assert.deepEqual(buildEspansoMatches([sensitive(';pw', 'pw')], {secrets: {}}).matches, [], 'no secrets.json: not expanded');
  assert.deepEqual(buildEspansoMatches([sensitive(';pw', 'pw')]).matches, [], 'none given: not expanded');
});

test('text with {{ goes through an echo variable; other text is the replace itself', () => {
  assert.deepEqual(literalToEspanso('plain {date} text'), {replace: 'plain {date} text', vars: []});
  assert.deepEqual(literalToEspanso('a {{b}} c').replace, '{{slated_text}}');
  assert.deepEqual(literalToEspanso(null), {replace: '', vars: []});
  const yaml = espansoYaml(buildEspansoMatches([sensitive(';pw', 'pw')], {secrets: {pw: 'x{{y}}"\n'}}).matches);
  assert.equal(yaml, [
    '# Generated by Slated from ~/.config/slated/config.json (hotstrings).',
    '# Slated rewrites this file when the configuration changes: edit hotstrings in Slated instead.',
    'matches:',
    '  - trigger: ";pw"',
    '    replace: "{{slated_text}}"',
    '    force_mode: keys',
    '    vars:',
    '      - name: slated_text',
    '        type: echo',
    '        params:',
    '          echo: "x{{y}}\\"\\n"',
    '        inject_vars: false',
    '',
  ].join('\n'));
  assert.ok(!yaml.includes('sensitive'), 'the marker isn’t written');
});

test('the match file holds sensitive text, so it’s readable only by you; the log never has the text', () => {
  const home = mkdtempSync(join(tmpdir(), 'slated-espanso-'));
  homes.push(home);
  const configDir = join(home, '.config/espanso');
  mkdirSync(join(configDir, 'match'), {recursive: true});
  const log = new MemoryLog();
  const sync = new EspansoSync({log, configDir, home});
  const config = {general: {hotstringsEnabled: true}, hotstrings: [sensitive(';pw', 'pw'), hotstring({trigger: ';hi', replacement: 'hello'})]};
  const result = sync.apply(config, {secrets: {pw: 'hunter2-text'}});
  assert.deepEqual(result, {engine: 'espanso', espansoInstalled: true, matchFile: sync.matchFile, count: 2});
  assert.equal(statSync(sync.matchFile).mode & 0o777, 0o600);
  assert.ok(readFileSync(sync.matchFile, 'utf8').includes('hunter2-text'), 'espanso needs the text');
  assert.deepEqual(log.named('espanso.written').at(-1).data, {path: sync.matchFile, count: 2, skipped: 0, sensitive: 1});
  // A file made readable by others since (or by an older Slated) is made private again, unchanged or not.
  const text = readFileSync(sync.matchFile, 'utf8');
  rmSync(sync.matchFile);
  writeFileSync(sync.matchFile, text, {mode: 0o644});
  sync.apply(config, {secrets: {pw: 'hunter2-text'}});
  assert.equal(statSync(sync.matchFile).mode & 0o777, 0o600);
  // Its text missing: left out, and the log names the trigger only.
  sync.apply(config, {secrets: {}});
  assert.ok(!readFileSync(sync.matchFile, 'utf8').includes('hunter2-text'), 'gone from espanso’s file');
  const unsupported = log.named('hotstrings.unsupported').at(-1).data.items;
  assert.deepEqual(unsupported, [{trigger: ';pw', skipped: "sensitive, and its text isn't on this computer yet (secrets.json)"}]);
  assert.ok(!JSON.stringify(log.events).includes('hunter2'), 'never in the log');
  sync.destroy();
});
