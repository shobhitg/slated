import AppKit
import Foundation
import SlatedScript

@testable import SlatedCore
@testable import SlatedSystem

// What the pasteboard says about a copy (concealed, transient, the app that made it) and how a secret
// goes back on it, on private pasteboards (the user's clipboard is never touched); how typing splits
// text into key events; and that Slate imports never make secrets.

private final class Copies: @unchecked Sendable {
  var list: [PasteboardWatcher.Copy] = []
}

/// The copy a watcher reports for a pasteboard holding `types` (type → string).
@MainActor private func copy(_ types: [String: String]) -> PasteboardWatcher.Copy? {
  let pasteboard = NSPasteboard(name: NSPasteboard.Name("io.github.slated.test.\(UUID().uuidString)"))
  defer { pasteboard.releaseGlobally() }
  let watcher = PasteboardWatcher(pasteboard: pasteboard)
  let copies = Copies()
  watcher.onCopy = { copies.list.append($0) }
  pasteboard.clearContents()
  for (type, value) in types { pasteboard.setString(value, forType: NSPasteboard.PasteboardType(type)) }
  watcher.poll()
  return copies.list.last
}

private let text = NSPasteboard.PasteboardType.string.rawValue

let secretPasteboardTests = Suite(
  "SecretPasteboard",
  [
    (
      "concealed copies are secrets; transient ones are not the user's; both together is a secret",
      {
        MainActor.assumeIsolated {
          let concealed = copy([text: "hunter2", "org.nspasteboard.ConcealedType": ""])
          expect(concealed?.isConcealed == true && concealed?.isTransient == false)
          let onePassword = copy([text: "hunter2", "com.agilebits.onepassword": ""])
          expect(onePassword?.isConcealed == true)
          for marker in [
            "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
            "com.typeit4me.clipping", "Pasteboard generator type",
          ] {
            let transient = copy([text: "a snippet", marker: ""])
            expect(transient?.isTransient == true && transient?.isConcealed == false, marker)
          }
          let both = copy([text: "hunter2", "org.nspasteboard.ConcealedType": "", "org.nspasteboard.TransientType": ""])
          expect(both?.isConcealed == true && both?.isTransient == true)
          let plain = copy([text: "hello"])
          expect(plain?.isConcealed == false && plain?.isTransient == false)
        }
      }
    ),
    (
      "the app a copy names is its source; an empty name doesn't count",
      {
        MainActor.assumeIsolated {
          let named = copy([text: "hunter2", "org.nspasteboard.source": "com.1password.1password"])
          expectEqual(named?.sourceApp, "com.1password.1password")
          let empty = copy([text: "x", "org.nspasteboard.source": ""])
          expect(empty?.sourceApp != "", "falls back to the app in front")
        }
      }
    ),
    (
      "a secret goes back marked concealed; anything else doesn't",
      {
        MainActor.assumeIsolated {
          let pasteboard = NSPasteboard(name: NSPasteboard.Name("io.github.slated.test.\(UUID().uuidString)"))
          defer { pasteboard.releaseGlobally() }
          PasteboardWatcher.write("hunter2", to: pasteboard, secret: true)
          expectEqual(pasteboard.string(forType: .string), "hunter2")
          expect(pasteboard.types?.contains(PasteboardWatcher.concealedType) == true)
          PasteboardWatcher.write("hello", to: pasteboard)
          expectEqual(pasteboard.string(forType: .string), "hello")
          expect(pasteboard.types?.contains(PasteboardWatcher.concealedType) != true)
        }
      }
    ),
    (
      "typing splits text into key events of at most 20 UTF-16 units, never inside a character's scalar",
      {
        let samples = [
          "abc", String(repeating: "a", count: 30), "👨‍👩‍👧‍👦", "🏴󠁧󠁢󠁳󠁣󠁴󠁿x", "P@ss{w0rd} 👍🏽 é", "e\u{301}" + String(repeating: "😀", count: 15),
        ]
        for sample in samples {
          let chunks = TextInjector.unicodeChunks(sample)
          expect(chunks.allSatisfy { $0.count <= 20 && !$0.isEmpty }, sample)
          expectEqual(chunks.flatMap { $0 }, Array(sample.utf16))
          // No chunk ends with a lone high surrogate or starts with a low one.
          for chunk in chunks {
            expect(!UTF16.isLeadSurrogate(chunk.last!) && !UTF16.isTrailSurrogate(chunk.first!), sample)
          }
        }
        expectEqual(TextInjector.unicodeChunks("abc").count, 1)
        expectEqual(TextInjector.unicodeChunks(String(repeating: "a", count: 30)).map(\.count), [20, 10])
        expectEqual(TextInjector.unicodeChunks(""), [])
      }
    ),
    (
      "importing a Slate config never makes a secret",
      {
        MainActor.assumeIsolated {
          let files = [
            "/x/.slate": "bind a:ctrl;alt push left\n",
            "/x/.slate.js": #"slate.bind("b:ctrl,alt", slate.operation("push", {direction: "right"}));"#,
          ]
          for path in files.keys.sorted() {
            let imported = SlateConfigImport.importFile(path, displayPath: path) { files[$0] }
            var config = SlatedConfiguration()
            _ = config.merge(imported)
            expect(!config.bindings.isEmpty, "\(path) imported")
            expect(config.secrets.isEmpty && !config.hotstrings.contains(where: \.isSensitive), path)
          }
        }
      }
    ),
  ])
